const AUTHORIZED_MOVIE_HOSTS = new Set(['video.blender.org', 'www.youtube.com', 'www.youtube-nocookie.com']);
const AUTHORIZED_LIVE_HOSTS = new Set(['www.youtube.com', 'www.youtube-nocookie.com']);

function normalizeText(value = '') {
  return String(value)
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, ' ')
    .trim();
}

function searchableText(item) {
  return normalizeText([
    item.title,
    item.year,
    item.studio,
    item.broadcaster,
    item.description,
    item.license,
    item.source,
    item.kind,
    ...(item.tags || [])
  ].filter(Boolean).join(' '));
}

export function searchCatalog(items, query) {
  const tokens = normalizeText(query).split(/\s+/).filter(Boolean);
  if (!tokens.length) return [...items];
  return items.filter(item => {
    const haystack = searchableText(item);
    return tokens.every(token => haystack.includes(token));
  });
}

export function filterCatalog({ mode = 'all', query = '', savedIds = new Set() } = {}) {
  let items = [...MOVIES, ...LIVE_CHANNELS];
  if (mode === 'movies') items = [...MOVIES];
  if (mode === 'live') items = [...LIVE_CHANNELS];
  if (mode === 'saved') items = items.filter(item => savedIds.has(item.id));
  items = searchCatalog(items, query);
  if (mode === 'movies' || mode === 'all') {
    items = [...items].sort((a, b) => {
      if (a.kind !== b.kind) return a.kind === 'movie' ? -1 : 1;
      return (b.year || 0) - (a.year || 0) || a.title.localeCompare(b.title);
    });
  }
  return items;
}

export function buildPlaybackUrl(item) {
  if (item.kind === 'live') {
    return `https://www.youtube.com/embed/live_stream?channel=${encodeURIComponent(item.channelId)}&autoplay=1&playsinline=1&rel=0`;
  }
  if (item.provider === 'youtube') {
    return `https://www.youtube-nocookie.com/embed/${encodeURIComponent(item.videoId)}?autoplay=1&playsinline=1&rel=0`;
  }
  return `https://video.blender.org/videos/embed/${encodeURIComponent(item.shortId)}?autoplay=1&warningTitle=0&peertubeLink=1&p2p=0`;
}

export function buildWatchUrl(item) {
  if (item.kind === 'live') return `https://www.youtube.com/channel/${encodeURIComponent(item.channelId)}/live`;
  if (item.provider === 'youtube') return `https://www.youtube.com/watch?v=${encodeURIComponent(item.videoId)}`;
  return `https://video.blender.org/w/${encodeURIComponent(item.shortId)}`;
}

export function isAuthorizedSource(item) {
  try {
    const embed = new URL(buildPlaybackUrl(item));
    const watch = new URL(buildWatchUrl(item));
    const allowed = item.kind === 'live' ? AUTHORIZED_LIVE_HOSTS : AUTHORIZED_MOVIE_HOSTS;
    return allowed.has(embed.hostname) && allowed.has(watch.hostname);
  } catch {
    return false;
  }
}

function initMovieXYZ() {
  const $ = selector => document.querySelector(selector);
  const $$ = selector => [...document.querySelectorAll(selector)];
  const storageKey = 'moviexyz_saved_v3';
  let mode = 'all';
  let query = '';
  let activeId = null;
  let playerTimer = null;

  const catalog = () => [...MOVIES, ...LIVE_CHANNELS];
  const findItem = id => catalog().find(item => item.id === id);
  const savedIds = () => {
    try { return new Set(JSON.parse(localStorage.getItem(storageKey) || '[]')); }
    catch { return new Set(); }
  };
  const saveIds = ids => localStorage.setItem(storageKey, JSON.stringify([...ids]));

  function toast(message) {
    const el = $('#toast');
    if (!el) return;
    el.textContent = message;
    el.classList.add('show');
    clearTimeout(toast.timer);
    toast.timer = setTimeout(() => el.classList.remove('show'), 1900);
  }

  function itemArtwork(item) {
    if (item.kind === 'live') {
      const initials = item.title.split(/\s+/).slice(0, 2).map(part => part[0]).join('').toUpperCase();
      return `<div class="liveArt" aria-hidden="true"><span>${initials}</span><b>LIVE TV</b></div>`;
    }
    if (item.thumbId) {
      return `<img src="https://i.ytimg.com/vi/${item.thumbId}/hqdefault.jpg" alt="${item.title} thumbnail" loading="lazy">`;
    }
    return `<div class="liveArt movieArt" aria-hidden="true"><span>▶</span><b>OPEN MOVIE</b></div>`;
  }

  function render() {
    const items = filterCatalog({ mode, query, savedIds: savedIds() });
    const grid = $('#grid');
    if (!grid) return;
    $('#count').textContent = `${items.length} result${items.length === 1 ? '' : 's'}`;

    const headings = { all: 'Movies & Live TV', movies: 'Open Movie Collection', live: 'Philippine Live TV', saved: 'My List' };
    $('#title').textContent = query ? `Search results for “${query}”` : headings[mode];

    if (!items.length) {
      grid.innerHTML = '<div class="empty"><strong>No results found.</strong><span>Try another movie title, year, studio, broadcaster, or keyword.</span></div>';
      return;
    }

    grid.innerHTML = items.map(item => `
      <article class="card ${item.kind === 'live' ? 'liveCard' : ''}" data-id="${item.id}" tabindex="0" role="button" aria-label="${item.kind === 'live' ? 'Watch' : 'Play'} ${item.title}">
        <div class="poster">
          ${itemArtwork(item)}
          <span class="tag ${item.kind === 'live' ? 'liveTag' : ''}">${item.kind === 'live' ? '● LIVE TV' : '✓ VERIFIED'}</span>
          <span class="playBadge">▶ ${item.kind === 'live' ? 'Watch Live' : 'Play'}</span>
        </div>
        <div class="body">
          <h3>${item.title}</h3>
          <p>${item.kind === 'live' ? item.broadcaster : `${item.year} • ${item.studio}`}</p>
          <p>${item.kind === 'live' ? 'Official channel • live when available' : item.license}</p>
        </div>
      </article>`).join('');
  }

  function updateFavoriteButton() {
    const item = findItem(activeId);
    if (!item || !$('#fav')) return;
    $('#fav').textContent = savedIds().has(activeId) ? '✓ In My List' : '＋ My List';
  }

  function openItem(id) {
    const item = findItem(id);
    if (!item || !isAuthorizedSource(item)) {
      toast('No verified playback source is available for this item.');
      return;
    }

    activeId = id;
    $('#mt').textContent = item.title;
    $('#md').textContent = item.description;
    $('#mm').innerHTML = item.kind === 'live'
      ? `<span>LIVE TV</span><span>• ${item.broadcaster}</span><span>• ${item.source}</span>`
      : `<span>${item.year}</span><span>• ${item.studio}</span><span>• ${item.license}</span>`;
    $('#official').href = buildWatchUrl(item);
    $('#official').textContent = item.kind === 'live' ? 'Open Official Channel ↗' : 'Open Official Source ↗';
    $('#frame').src = buildPlaybackUrl(item);
    $('#playerStatus').textContent = item.kind === 'live'
      ? 'Loading the official channel live player…'
      : 'Loading the verified official movie player…';
    $('#modal').hidden = false;
    document.body.style.overflow = 'hidden';
    updateFavoriteButton();

    clearTimeout(playerTimer);
    playerTimer = setTimeout(() => {
      if (!$('#modal').hidden) {
        $('#playerStatus').textContent = item.kind === 'live'
          ? 'If the channel is off-air or embedding is unavailable, open the official channel below.'
          : 'If playback does not start, open the official source below.';
      }
    }, 6500);
  }

  function closePlayer() {
    clearTimeout(playerTimer);
    $('#frame').src = 'about:blank';
    $('#modal').hidden = true;
    document.body.style.overflow = '';
    activeId = null;
  }

  function toggleFavorite() {
    if (!activeId) return;
    const ids = savedIds();
    if (ids.has(activeId)) {
      ids.delete(activeId);
      toast('Removed from My List');
    } else {
      ids.add(activeId);
      toast('Added to My List');
    }
    saveIds(ids);
    updateFavoriteButton();
    render();
  }

  $('#grid')?.addEventListener('click', event => {
    const card = event.target.closest('[data-id]');
    if (card) openItem(card.dataset.id);
  });
  $('#grid')?.addEventListener('keydown', event => {
    if ((event.key === 'Enter' || event.key === ' ') && event.target.matches('[data-id]')) {
      event.preventDefault();
      openItem(event.target.dataset.id);
    }
  });

  $$('[data-f]').forEach(button => button.addEventListener('click', () => {
    mode = button.dataset.f;
    $$('[data-f]').forEach(item => item.classList.toggle('on', item === button));
    render();
    document.querySelector('.wrap')?.scrollIntoView({ behavior: 'smooth', block: 'start' });
  }));

  $('#heroPlay')?.addEventListener('click', () => openItem('singularity'));
  $('#heroLive')?.addEventListener('click', () => {
    mode = 'live';
    $$('[data-f]').forEach(item => item.classList.toggle('on', item.dataset.f === 'live'));
    render();
    document.querySelector('.wrap')?.scrollIntoView({ behavior: 'smooth', block: 'start' });
  });
  $('#close')?.addEventListener('click', closePlayer);
  $('#modal')?.addEventListener('click', event => { if (event.target === $('#modal')) closePlayer(); });
  $('#fav')?.addEventListener('click', toggleFavorite);

  $('#q')?.addEventListener('input', event => {
    query = event.target.value.trim();
    $('#clearSearch').hidden = !query;
    render();
  });
  $('#clearSearch')?.addEventListener('click', () => {
    query = '';
    $('#q').value = '';
    $('#clearSearch').hidden = true;
    $('#q').focus();
    render();
  });
  $('#searchBtn')?.addEventListener('click', () => {
    $('#q')?.focus();
    document.querySelector('.search')?.scrollIntoView({ behavior: 'smooth', block: 'center' });
  });
  $('#frame')?.addEventListener('load', () => {
    if ($('#frame').src !== 'about:blank') $('#playerStatus').textContent = 'Official player loaded. If it does not play, use the official-source button.';
  });
  document.addEventListener('keydown', event => {
    if (event.key === 'Escape' && !$('#modal')?.hidden) closePlayer();
    if (event.key === '/' && $('#modal')?.hidden && document.activeElement?.tagName !== 'INPUT') {
      event.preventDefault();
      $('#q')?.focus();
    }
  });

  render();
  setTimeout(() => toast(`${MOVIES.length} open movies • ${LIVE_CHANNELS.length} official live channels`), 450);
}

if (typeof document !== 'undefined') {
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', initMovieXYZ);
  else initMovieXYZ();
}
